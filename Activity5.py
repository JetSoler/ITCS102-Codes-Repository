# + - addition
# - - subtraction
# * - multiplication
# / - division
# // - floor division
# ** - exponentation
# % - modulus

a = 45
b = 23
sum = a+b

print("The sum of a + b is ", sum)
print("The sum of a - b is ", 45-23)
print("The sum of a * b is ", 45*23)
print("The sum of a / b is ", 45/23)
print("The sum of a // b is ", 45//23)
print("The sum of a ** b is ", 45**23)
print("The sum of a % b is ", 45%23)